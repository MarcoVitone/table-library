export function createTableTranslator(config: ITableLocalization = {}): TTableTranslator {
  const base = config.locale?.toLowerCase().split(/[-_]/)[0] === "it" ? italianTableMessages : englishTableMessages;
  return (key, values = {}) => {
    const message = config.messages?.[key] ?? base[key];
    const text = typeof message === "function" ? message(values) : message;
    return text.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  };
}

